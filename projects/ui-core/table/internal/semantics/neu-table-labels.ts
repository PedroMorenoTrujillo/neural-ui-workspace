export function tableMessage(
  overrides: NeuTableLabels['messages'],
  key: NeuTableMessage,
  values: Readonly<Record<string, string | number>> = {},
): string {
  return (overrides?.[key] ?? messages[key]).replace(/\{(\w+)\}/g, (match, name: string) =>
    String(values[name] ?? match),
  );
}
